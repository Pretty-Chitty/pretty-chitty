#!/usr/bin/env node
// Renders the Petty Market tutorial narration to MP3 with the system's text-to-speech (macOS `say`),
// one file per step, plus exact sentence timings: every sentence is rendered on its own, measured,
// and the clips are concatenated, so `sentenceTimes` is right by construction.
//
//   yarn demo:audio            # all locales
//   yarn demo:audio es         # one locale
//
// Output: ./<locale>/<step>.mp3 and ./index.ts (imports + timings), both committed. Replace the MP3s
// with studio recordings any time; re-run with --timings-only to keep the files and only re-measure.
// Requirements: macOS `say`, and ffmpeg/ffprobe on PATH.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const only = args.find((a) => !a.startsWith("--"));
const timingsOnly = args.includes("--timings-only");

// Must match splitSentences() in src/library/game/tutorial/defineTutorial.ts
const splitSentences = (text) =>
  text
    .split(/(?<=[.!?][")'\]]*)\s+(?=\S)/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);

/** Markdown and :tokens: to words a voice can read */
function spoken(markdown, spokenTokens) {
  return markdown
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "") // images
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // links
    .replace(/:([a-zA-Z0-9_-]+):/g, (m, name) => spokenTokens[name] ?? name)
    .replace(/^#+\s*/gm, "")
    .replace(/^\s*[-*]\s+/gm, "")
    .replace(/[*_`>]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

const probe = (file) =>
  parseFloat(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString());

const locales = readdirSync(here)
  .filter((f) => /^strings\.[a-z-]+\.json$/i.test(f))
  .map((f) => JSON.parse(readFileSync(join(here, f), "utf8")))
  .filter((s) => !only || s.locale === only);

const index = {};
for (const strings of locales) {
  const { locale, voice } = strings;
  const outDir = join(here, locale);
  mkdirSync(outDir, { recursive: true });
  index[locale] = {};
  for (const [step, text] of Object.entries(strings.steps)) {
    const sentences = splitSentences(text).map((s) => spoken(s, strings.spoken));
    const mp3 = join(outDir, `${step}.mp3`);
    const tmp = mkdtempSync(join(tmpdir(), "narration-"));
    const clips = [];
    const times = [];
    let t = 0;
    sentences.forEach((sentence, i) => {
      times.push(Math.round(t * 1000) / 1000);
      if (!sentence) return; // an image-only "sentence" takes no time
      const clip = join(tmp, `${i}.aiff`);
      execFileSync("say", ["-v", voice, "-o", clip, sentence]);
      clips.push(clip);
      t += probe(clip) + 0.25; // the pause `say` leaves between separate renders is ~0; add a beat
    });
    if (!timingsOnly || !existsSync(mp3)) {
      // concat with a 0.25 s gap between sentences, matching the timings above
      const list = join(tmp, "list.txt");
      const silence = join(tmp, "gap.aiff");
      execFileSync("ffmpeg", ["-v", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=22050:cl=mono", "-t", "0.25", silence]);
      writeFileSync(list, clips.map((c) => `file '${c}'\nfile '${silence}'`).join("\n") + "\n");
      execFileSync("ffmpeg", [
        "-v", "error", "-y", "-f", "concat", "-safe", "0", "-i", list,
        "-ar", "22050", "-ac", "1", "-codec:a", "libmp3lame", "-b:a", "64k", mp3,
      ]);
    }
    rmSync(tmp, { recursive: true, force: true });
    index[locale][step] = { file: `./${locale}/${step}.mp3`, sentenceTimes: times, duration: Math.round(t * 1000) / 1000 };
    console.log(`${locale}/${step}.mp3  ${sentences.length} sentence(s)  ${index[locale][step].duration}s`);
  }
}

// Generated TypeScript: static imports so webpack bundles the files as assets
const lines = [
  "// GENERATED by generate.mjs — do not edit. Re-run `yarn demo:audio` after changing strings.*.json.",
  "/* eslint-disable */",
];
const names = [];
for (const [locale, steps] of Object.entries(index)) {
  for (const [step, info] of Object.entries(steps)) {
    const name = `${locale}_${step}`.replace(/[^a-zA-Z0-9_]/g, "_");
    names.push([locale, step, name, info]);
    lines.push(`import ${name} from "${info.file}";`);
  }
}
lines.push("", "export type Narration = { url: string; sentenceTimes: number[]; duration: number };", "");
lines.push("export const narration: { [locale: string]: { [stepId: string]: Narration } } = {");
for (const locale of Object.keys(index)) {
  lines.push(`  ${JSON.stringify(locale)}: {`);
  for (const [l, step, name, info] of names) {
    if (l !== locale) continue;
    lines.push(`    ${JSON.stringify(step)}: { url: ${name}, sentenceTimes: ${JSON.stringify(info.sentenceTimes)}, duration: ${info.duration} },`);
  }
  lines.push("  },");
}
lines.push("};", "");
writeFileSync(join(here, "index.ts"), lines.join("\n"));
console.log(`wrote ${join(here, "index.ts")}`);
